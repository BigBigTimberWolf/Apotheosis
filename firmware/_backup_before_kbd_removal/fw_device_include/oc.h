#pragma once
// ============================================================
// oc.h - CPU超频管理器(带自愈保险)
// 260MHz: 几乎全芯片稳 | 280MHz: 多数稳 | 更高看体质
// 原理: .noinit 段存"连续崩溃起点" → 启动时若检测到上次异常复位, 本轮不升频并记账;
//       连续 2 次异常复位则永久降回 240 并禁用.
//
// 类型说明: 频率一律用 uint32_t。原实现用 uint8_t 装 260, 编译器会截断成 4
// (-Woverflow), 于是 apply(4) 必然失败 -> 超频被永久禁用, 整段逻辑是死代码。
// ============================================================
#include <cstdint>

namespace oc {

// 尝试切换CPU频率并验证; 成功返回true
bool apply(uint32_t mhz);

// 开机自检流程:
//  1. 读 .noinit 里的崩溃计数与"上次启动是否走完自检"标志
//  2. 若上轮启动未走完自检(异常复位): 计数+1, 本轮不升频(只用安全频率)
//  3. 若计数>=2: 永久禁用超频, 计数清零, 跑240
//  4. 否则(干净启动)才尝试升到目标频率
//  5. 运行30s后由 confirmStable() 记账为"稳定"
void bootSelfTest();

// 开机30s后调用: 系统没崩说明这档频率稳了, 清除崩溃计数
void confirmStable();

uint32_t currentMhz();
bool     enabled();     // 是否允许超频
void     setEnabled(bool on, uint32_t target_mhz);

} // namespace oc
